#!/usr/bin/env node
// Writes the AgentMandate ABI (packages/aevum and the @agentmeter/sdk package) from the compiled contract, so the TypeScript side
// always matches the Solidity. Run after changing AgentMandate.sol:  make abi
import { readFileSync, writeFileSync } from "node:fs";
const out = JSON.parse(readFileSync("contracts/out/AgentMandate.sol/AgentMandate.json", "utf8"));
const abi = out.abi.filter((x) => x.type !== "constructor");
const ts = `// GENERATED by tools/gen-abi.mjs from contracts/src/AgentMandate.sol. Do not edit; run \`make abi\`.\nexport const agentMandateAbi = ${JSON.stringify(abi, null, 2)} as const;\n`;
writeFileSync("packages/aevum/src/agentMandateAbi.ts", ts);
writeFileSync("packages/sdk/src/abi.ts", ts);
console.log(`agentMandateAbi: ${abi.length} entries written`);
